// Isolated PostgreSQL checks for guest permissions and content-only knocks.
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
const { PGlite } = await import(process.env.PGLITE_MODULE || '@electric-sql/pglite');
const db = new PGlite();
const owner = '00000000-0000-0000-0000-000000000001';
const visitor = '00000000-0000-0000-0000-000000000002';
const stranger = '00000000-0000-0000-0000-000000000003';
const house = '00000000-0000-0000-0000-000000000004';
const content = '00000000-0000-0000-0000-000000000005';
const login = async id => db.query("select set_config('request.jwt.claim.sub', $1, false)", [id]);
try {
  await db.exec(`
    create role authenticated;
    create schema auth;
    create function auth.uid() returns uuid language sql stable as
      $$ select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid $$;
    create table public."case" (owner_id uuid, campanello_hinoo_id uuid);
    create table public.honoo (id uuid primary key, user_id uuid, recipient_tag text, text text, image_url text, created_at timestamptz);
    create table public.hinoo (id uuid primary key, user_id uuid, recipient_tag text, pages jsonb, created_at timestamptz);
    create table public.house_access (
      id bigint generated by default as identity primary key,
      visitor_id uuid, target_house_tag text, honoo_id uuid, hinoo_id uuid,
      share_modes text[] not null default '{}', granted_at timestamp,
      created_at timestamptz not null default now()
    );
    alter table public.house_access enable row level security;
    grant usage on schema public, auth to authenticated;
    grant select on public."case", public.honoo, public.hinoo to authenticated;
    grant insert on public.house_access to authenticated;
    grant usage on sequence public.house_access_id_seq to authenticated;
    insert into public."case" values ('${owner}', '${house}');
    insert into public.honoo values ('${content}', '${visitor}', '${house}', 'Bussata', 'https://example.test/honoo.png', '2026-01-01');
    insert into public.hinoo values ('${content}', '${visitor}', '${house}', '[{"text":"Bussata hinoo","backgroundImage":"https://example.test/hinoo.png"}]', '2026-01-02');
    insert into public."case" values ('${owner}', '00000000-0000-0000-0000-000000000099');
    insert into public.house_access (id, visitor_id, target_house_tag, share_modes, granted_at)
      values (999, '${visitor}', '00000000-0000-0000-0000-000000000099', array['home','moon'], '2026-01-01');
  `);
  await db.exec(await readFile(new URL('../supabase/migrations/20261013120000_house_guests_permissions.sql', import.meta.url), 'utf8'));
  await db.exec(await readFile(new URL('../supabase/migrations/20261013150000_house_guest_first_content.sql', import.meta.url), 'utf8'));
  await db.exec(`
    create table public.users(auth_user_id uuid, address text);
    alter table public.honoo add column conversation_id text default 'honoo-conversation';
    alter table public.hinoo add column conversation_id text default 'hinoo-conversation';
  `);
  await db.exec(await readFile(new URL('../supabase/migrations/20261017120000_house_request_conversations.sql', import.meta.url), 'utf8'));
  await login(owner);
  await db.exec('set role authenticated');
  const legacyGuests = (await db.query('select * from public.get_house_guests($1)', ['00000000-0000-0000-0000-000000000099'])).rows;
  assert.equal(legacyGuests.length, 1, 'existing approvals without content must survive the migrations');
  assert.deepEqual(legacyGuests[0].share_modes, ['home', 'moon']);
  assert.equal(legacyGuests[0].honoo, null);
  assert.equal(legacyGuests[0].hinoo, null);
  await db.exec('reset role');
  await login(visitor);
  await db.exec('set role authenticated');
  const insert = (extra = '', values = '') => db.exec(`insert into public.house_access(visitor_id,target_house_tag${extra}) values ('${visitor}','${house}'${values})`);
  await assert.rejects(() => insert(), /row-level security/);
  await assert.rejects(() => insert(',honoo_id,hinoo_id', `,'${content}','${content}'`), /row-level security/);
  await assert.rejects(() => insert(',honoo_id,share_modes', `,'${content}',array['all']`), /row-level security/);
  await insert(',honoo_id', `,'${content}'`);
  await insert(',hinoo_id', `,'${content}'`);
  await login(owner);
  const inbox = (await db.query('select * from public.get_house_inbox($1)', [house])).rows;
  assert.equal(inbox.length, 2);
  assert.ok(inbox.every(row => row.granted_at === null && row.share_modes.length === 0));
  assert.equal(inbox[0].honoo.text, 'Bussata');
  assert.equal(inbox[1].hinoo.pages[0].text, 'Bussata hinoo');
  for (const conversation of ['honoo-conversation', 'hinoo-conversation']) {
    assert.equal((await db.query('select public.is_conversation_participant($1) allowed', [conversation])).rows[0].allowed, true);
  }
  await login(stranger);
  assert.equal((await db.query('select * from public.get_house_inbox()')).rows.length, 0);
  assert.equal((await db.query("select public.is_conversation_participant('honoo-conversation') allowed")).rows[0].allowed, false);
  await assert.rejects(() => insert(',honoo_id', `,'${content}'`), /row-level security/);
  assert.equal((await db.query('select * from public.get_house_guests($1)', [house])).rows.length, 0);
  await assert.rejects(() => db.query("select public.update_house_guest_access(4,array['all'])"), /not found/);
  await db.exec('reset role');
  const { rows: [{ id }] } = await db.query('select min(id) id from public.house_access');
  await db.query("update public.house_access set granted_at=now(), share_modes=array['home'] where id=$1", [id]);
  await login(owner);
  await db.exec('set role authenticated');
  let rows = (await db.query('select * from public.get_house_guests($1)', [house])).rows;
  assert.equal(rows.length, 1);
  assert.equal(rows[0].honoo.text, 'Bussata');
  await db.query("select public.update_house_guest_access($1,'{}')", [id]);
  rows = (await db.query('select * from public.get_house_guests($1)', [house])).rows;
  assert.equal(rows.length, 1, 'revoked guests must remain manageable');
  assert.deepEqual(rows[0].share_modes, []);
  await db.query("select public.update_house_guest_access($1,array['moon','moon'])", [id]);
  rows = (await db.query('select * from public.get_house_guests($1)', [house])).rows;
  assert.deepEqual(rows[0].share_modes, ['moon']);
  await assert.rejects(() => db.query("select public.update_house_guest_access($1,array['invalid'])", [id]), /Invalid/);
  assert.equal(rows[0].honoo.image_url, 'https://example.test/honoo.png');
  assert.equal(rows[0].hinoo, null);
  // Legacy approvals without content pointers still show the first sent content.
  await db.exec('reset role');
  await db.query('update public.house_access set honoo_id=null where id=$1', [id]);
  await db.exec('set role authenticated');
  rows = (await db.query('select * from public.get_house_guests($1)', [house])).rows;
  assert.equal(rows[0].honoo.text, 'Bussata');
  // Selection is chronological across both types, with complete image + text.
  await db.exec('reset role');
  await db.exec("update public.hinoo set created_at='2025-12-01'");
  await db.exec('set role authenticated');
  rows = (await db.query('select * from public.get_house_guests($1)', [house])).rows;
  assert.equal(rows[0].honoo, null);
  assert.equal(rows[0].hinoo.pages[0].text, 'Bussata hinoo');
  assert.equal(rows[0].hinoo.pages[0].backgroundImage, 'https://example.test/hinoo.png');
  // Never substitute another visitor's content when this guest has none.
  await db.exec('reset role');
  await db.exec(`update public.hinoo set user_id='${stranger}'; update public.honoo set recipient_tag='another-house'`);
  await db.exec('set role authenticated');
  rows = (await db.query('select * from public.get_house_guests($1)', [house])).rows;
  assert.equal(rows[0].honoo, null);
  assert.equal(rows[0].hinoo, null);
  await login(visitor);
  await assert.rejects(() => db.query("select public.update_house_guest_access($1,array['all'])", [id]), /not found/);
  await db.exec('reset role');
  await db.exec(`
    alter table public.honoo add column reply_to uuid;
    alter table public.hinoo add column reply_to uuid;
    update public.honoo set recipient_tag='${house}', reply_to='${house}';
    update public.hinoo set user_id='${visitor}', recipient_tag='${house}', reply_to='${house}';
    insert into public.honoo (id,user_id,recipient_tag,reply_to)
      values ('00000000-0000-0000-0000-000000000100','${visitor}','${house}','${content}');
  `);
  await db.exec(await readFile(new URL('../supabase/migrations/20261019120000_house_followup_recipient.sql', import.meta.url), 'utf8'));
  assert.equal((await db.query("select recipient_tag from public.honoo where id='00000000-0000-0000-0000-000000000100'")).rows[0].recipient_tag, owner, 'repair existing follow-ups');
  for (const parentTable of ['honoo', 'hinoo']) {
    const parentId = crypto.randomUUID();
    await db.query(`insert into public.${parentTable} (id,user_id,recipient_tag,reply_to) values ($1,$2,$3::text,$3::text::uuid)`, [parentId, visitor, house]);
    assert.equal((await db.query(`select recipient_tag from public.${parentTable} where id=$1`, [parentId])).rows[0].recipient_tag, house, 'initial request stays on the house badge');
    for (const replyTable of ['honoo', 'hinoo']) {
      const replyId = crypto.randomUUID();
      const sent = (await db.query(`insert into public.${replyTable} (id,user_id,recipient_tag,reply_to) values ($1,$2,$3,$4) returning recipient_tag`, [replyId, visitor, house, parentId])).rows[0];
      assert.equal(sent.recipient_tag, owner, `${parentTable} → ${replyTable} must match owner reply notification filter`);
      const received = (await db.query(`insert into public.${parentTable} (id,user_id,recipient_tag,reply_to) values ($1,$2,$3,$4) returning recipient_tag`, [crypto.randomUUID(), owner, visitor, replyId])).rows[0];
      assert.equal(received.recipient_tag, visitor, 'owner response targets the visitor');
      const continued = (await db.query(`insert into public.${replyTable} (id,user_id,recipient_tag,reply_to) values ($1,$2,$3,$4) returning recipient_tag`, [crypto.randomUUID(), visitor, house, replyId])).rows[0];
      assert.equal(continued.recipient_tag, owner, 'stale client continues a normalized outgoing message');
    }
  }
  assert.equal((await db.query('select recipient_tag from public.honoo where id=$1', [content])).rows[0].recipient_tag, house);
  assert.deepEqual((await db.query('select share_modes from public.house_access where id=$1', [id])).rows[0].share_modes, ['moon'], 'sending messages must not change access permissions');
  console.log('House guests SQL: required content, owner-only updates, revocation and restoration passed.');
  console.log('House follow-ups SQL: initial requests, backfill, all Honoo/Hinoo combinations and replies passed.');
} finally { await db.close(); }
